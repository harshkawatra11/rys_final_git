"""Generate responsive home-page photo metadata and tiny inline previews."""
import base64
from io import BytesIO
import json
from pathlib import Path
import re

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]


def build_home_images():
    manifest = json.loads((ROOT / "images/optimized/manifest.json").read_text(encoding="utf-8"))
    sources = json.loads((ROOT / "scripts/home-image-sources.json").read_text(encoding="utf-8"))
    reverse = {v["url"]: name for name, item in manifest.items() for v in item["variants"]}

    def metadata(name, portrait=False):
        item = manifest[name]
        variants = list(item["variants"])
        if portrait:
            variants = [v for v in variants if v["width"] <= 960]
        if portrait and item["width"] > 240:
            url = variants[0]["url"].rsplit("-", 1)[0] + "-240w.webp"
            path = ROOT / url.lstrip("/")
            if not path.exists():
                with Image.open(ROOT / "images" / name) as original:
                    original = ImageOps.exif_transpose(original)
                    original = original.convert("RGBA" if "A" in original.getbands() else "RGB")
                    original.resize((240, round(original.height * 240 / original.width)), Image.Resampling.LANCZOS).save(path, "WEBP", quality=82, method=6)
            variants.insert(0, {"url": url, "width": 240})
        with Image.open(ROOT / variants[0]["url"].lstrip("/")) as image:
            image.thumbnail((32, 32))
            buffer = BytesIO()
            image.save(buffer, "WEBP", quality=35, method=4)
        return {
            "src": variants[0]["url"],
            "srcset": ", ".join(f'{v["url"]} {v["width"]}w' for v in variants),
            "width": item["width"], "height": item["height"],
            "preview": "data:image/webp;base64," + base64.b64encode(buffer.getvalue()).decode(),
        }

    html = (ROOT / "index.html").read_text(encoding="utf-8")
    urls = re.findall(r'<a class="carousel-slide"[\s\S]*?<img[^>]*\bsrc="([^"]+)"', html)
    data = {
        "portraits": {name: metadata(source, portrait=True) for name, source in sources.items()},
        "carousel": [metadata(reverse.get(url, url.removeprefix("/images/"))) for url in urls],
    }
    output = "/* Generated by scripts/prepare_home_images.py. */\nwindow.RYS_HOME_IMAGES = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n"
    (ROOT / "js/home-image-data.js").write_text(output, encoding="utf-8")
    print(f'Prepared {len(data["portraits"])} responsive portraits and {len(data["carousel"])} carousel previews.')


if __name__ == "__main__":
    build_home_images()
